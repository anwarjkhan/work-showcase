import { test } from 'vitest';
import { createSyntheticPortfolio } from '@/lib/data/synthetic';
import { computeAll, computePlanExtras } from '@/lib/engine';
import { DEMO_CLOCK } from '@/lib/config/clock';
test('probe', () => {
  const d = createSyntheticPortfolio();
  const r = computeAll(d, DEMO_CLOCK);
  const x = computePlanExtras(d, DEMO_CLOCK);
  console.log('IR', d.investmentRequests.map(i => `${i.id} ${i.ref} ${i.title} ${i.route}`).join('\n'));
  console.log('PM', d.pmNodes.map(i => `${i.id} ${i.level} p=${i.parentId} ir=${i.investmentRequestId} ${i.title} ${i.plannedStart}..${i.plannedEnd}`).join('\n'));
  console.log('spans', r.plan.spans.length, r.plan.start, r.plan.end);
  console.log(r.plan.spans.filter(s=>s.level!=='epic').map(s => `${s.level.padEnd(18)} ${s.entity.id} p=${s.parentId} ${s.plannedStart}..${s.plannedEnd} f=${s.forecastEnd} slip=${s.slipDays} late=${s.lateDependencyIds.join(',')} ms=${s.milestoneIds.length} | ${s.label}`).join('\n'));
  console.log('ms', d.milestones.map(m => `${m.id} ${m.deliverableId} ${m.date} reg=${m.regulatory} ${m.status} ${m.title}`).join('\n'));
  console.log('deps', d.dependencies.map(m => `${m.id} ${m.fromDeliverableId}->${m.toDeliverableId} need=${m.needBy} com=${m.committed} ${m.status} crit=${m.critical} ${m.title}`).join('\n'));
  console.log('knock', JSON.stringify(x.knockOn, null, 1));
  console.log('sprints', d.sprints.slice(0,8).map(s=>`${s.id} ${s.name} ${s.index} ${s.start}..${s.end}`).join('\n'));
  console.log('fc td-1001', JSON.stringify(x.forecasts.get('td-1001')));
  const wi = d.workItems.filter(w => w.sprintId);
  console.log('items with sprint', wi.length, 'of', d.workItems.length, 'types', [...new Set(d.workItems.map(w=>w.type))].join(','));
  const cur = d.sprints.find(s => s.start <= '2027-03-08' && s.end >= '2027-03-08');
  console.log('cur sprint', cur?.id, d.workItems.filter(w=>w.sprintId===cur?.id).length);
  console.log('outcomes sample', d.outcomes.slice(0,3).map(o=>`${o.id} ${o.deliverableId} ${o.dueDate} ${o.reportedStatus}`).join('\n'));
});
